async (page) => {
  const checks = [], errors = [], failedRequests = [];
  const check = (ok, label) => { if (!ok) throw Error(label); checks.push(label); };
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', response => { if (response.status() >= 400) failedRequests.push(`${response.status()} ${response.url()}`); });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:5190/?hfprod=' + Date.now() + '#human-fish');
  await page.locator('.hf-entry .launch-demo:not([disabled])').waitFor();
  if (await page.locator('.platform-locale').innerText() === 'JA') await page.locator('.platform-locale').click();
  check(await page.locator('.hf-cover-fish').evaluate(img => img.complete && img.naturalWidth > 0), 'production alias resolves and generated art loads');
  await page.locator('.launch-howto').click();
  check(await page.locator('#sheet-title').innerText().then(t => t.includes('HUMAN FISH')), 'public instructions and credits open');
  check(await page.locator('a[href="https://opentracks.com/bgm/detail/19143"]').count() > 0, 'music source is credited in the game');
  await page.keyboard.press('Escape');
  await page.locator('.launch-demo').click();
  await page.waitForFunction(() => document.querySelector('.hf-overlay')?.hidden && Number(document.querySelector('.hf-time')?.textContent) < 45);
  const move = async (x, y) => { const r = await page.locator('.hf-stage').boundingBox(); await page.mouse.click(r.x + r.width * x, r.y + r.height * y); };
  check(await page.locator('.hf-bite').evaluate(b => b.getBoundingClientRect().bottom <= innerHeight), 'production mobile bite control is visible');
  await move(.72, .53); await page.waitForTimeout(550); await page.locator('.hf-bite').click();
  await page.waitForFunction(() => document.querySelector('.hf-score').textContent === '3');
  check(true, 'public touch controls eat a shrimp in the built game');
  await move(.5, .155); await page.waitForTimeout(800);
  const oxygen = await page.locator('.hf-o2-value').innerText();
  await page.locator('.hf-bite').click();
  await page.waitForFunction(() => Number(document.querySelector('.hf-o2-value').textContent.match(/\d+/)[0]) >= 97);
  check(Number(oxygen.match(/\d+/)[0]) < 95, 'surface breath refills oxygen using the public button');
  await page.locator('.hf-se').click(); check(await page.locator('.hf-se').getAttribute('aria-pressed') === 'false', 'SE can be muted');
  await page.locator('.game-music').click();
  check(await page.locator('.game-music').getAttribute('aria-pressed') === 'false', 'BGM can be muted independently');
  await move(.5, .88);
  await page.locator('.hf-result').waitFor({ timeout: 24000 });
  await page.waitForTimeout(1000);
  check(await page.locator('.hf-result h2').innerText().then(t => t.includes('生きました')), 'unmanaged oxygen ends a real production life with a report');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'production report has no horizontal overflow');
  await page.screenshot({ path: 'output/playwright/human-fish-production-result.png', fullPage: true });
  await page.locator('[data-result-action="retry"]').click();
  await page.waitForFunction(() => document.querySelector('.hf-overlay')?.hidden && Number(document.querySelector('.hf-time')?.textContent) < 45);
  check(await page.locator('.hf-score').innerText() === '0', 'public retry resets the production life');
  await page.locator('.game-back').click();
  await page.waitForFunction(() => !document.querySelector('.hf-phaser-host canvas'));
  check(true, 'feed navigation removes the production canvas');
  check(errors.length === 0 && failedRequests.length === 0, 'no production browser errors or failed assets');
  return { checks, errors, failedRequests };
}
