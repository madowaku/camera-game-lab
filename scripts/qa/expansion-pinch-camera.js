// Synthetic landmarks traverse the real input normalization, projection and game.
async (page) => {
  const base = new URL(page.url()).origin, checks = [], errors = [];
  const check = (value, name) => { if (!value) throw Error(name); checks.push(name); };
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('camera-game-lab-locale', 'en'));
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto(base + '/?qa=pinch-camera#/game/solo-pinch-world');
  await page.waitForFunction(() => document.querySelector('.launch-camera')?.disabled === false);
  await page.clock.install();
  await page.clock.pauseAt(new Date(Date.now() + 100));
  await page.evaluate(async () => {
    const source = await (await fetch('/src/input/bodyInput.js')).text();
    const vision = await import(source.match(/from "([^"]*mediapipe[^"]*)"/)[1]);
    const { BodyInput } = await import('/src/input/bodyInput.js');
    const start = BodyInput.prototype.start;
    BodyInput.prototype.start = function () { Object.defineProperty(this.video, 'currentTime', { configurable: true, get: () => performance.now() / 1000 }); return start.call(this); };
    window.__hand = { present: true, closed: false, x: .23, y: .58 };
    window.__tracks = []; window.__contexts = []; window.__models = 0; window.__closes = 0; window.__mediaRequests = 0;
    const Audio = window.AudioContext;
    window.AudioContext = class extends Audio { constructor(...args) { super(...args); window.__contexts.push(this); } };
    vision.FilesetResolver.forVisionTasks = async () => ({});
    vision.GestureRecognizer.createFromOptions = async () => {
      window.__models++;
      return { close: () => window.__closes++, recognizeForVideo: () => {
        if (!__hand.present) return {};
        const x = 1 - __hand.x, y = .5 + (__hand.y - .5) * 360 / 640;
        const points = Array.from({ length: 21 }, () => ({ x, y }));
        return { landmarks: [points], gestures: [[{ categoryName: __hand.closed ? 'Closed_Fist' : 'Open_Palm', score: .95 }]] };
      } };
    };
    vision.FaceLandmarker.createFromOptions = async () => {
      window.__models++;
      return { setOptions: async () => {}, close: () => window.__closes++, detectForVideo: () => ({ faceLandmarks: [[{}, { x: .5, y: .4 }]], faceBlendshapes: [{ categories: ['eyeBlinkLeft', 'eyeBlinkRight'].map((categoryName) => ({ categoryName, score: .1 })) }] }) };
    };
    const canvas = document.createElement('canvas'); canvas.width = 360; canvas.height = 640;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#aaafa0'; ctx.fillRect(0, 0, 360, 640);
    window.__paint = setInterval(() => ctx.fillRect(0, 0, 360, 640), 30);
    const stream = () => { const s = canvas.captureStream(30); __tracks.push(...s.getTracks()); return s; };
    navigator.mediaDevices.getUserMedia = async () => {
      __mediaRequests++;
      if (window.__deny) throw new DOMException('QA denial', 'NotAllowedError');
      if (window.__delay) return new Promise((resolve) => { window.__grant = () => resolve(stream()); });
      return stream();
    };
    const raf = window.requestAnimationFrame, cancel = window.cancelAnimationFrame;
    window.__rafs = new Set();
    window.requestAnimationFrame = (fn) => { let id; id = raf((time) => { __rafs.delete(id); fn(time); }); __rafs.add(id); return id; };
    window.cancelAnimationFrame = (id) => { __rafs.delete(id); cancel(id); };
  });
  const set = async (values, ms = 120) => { await page.evaluate((data) => Object.assign(__hand, data), values); await page.clock.runFor(ms); };
  const held = () => page.locator('.pw-object').evaluate((el) => el.classList.contains('is-held'));
  const point = () => page.locator('.pw-object').evaluate((el) => { const matrix = el.transform.baseVal.getItem(0).matrix; return { x: matrix.e, y: matrix.f }; });
  await page.locator('.launch-camera').click(); await page.waitForFunction(() => document.querySelector('.pw-stage video')?.srcObject);
  await page.clock.runFor(1900);
  check((await page.locator('.pw-message').textContent()) === '', 'open raw hand passes readiness and countdown');
  await set({ x: .87, y: .84, closed: true }); await set({ x: .23, y: .58 }, 300);
  check(!(await held()), 'raw held fist overlap cannot auto-grab');
  await set({ closed: false }); await set({ closed: true }); check(await held(), 'raw fresh fist grabs');
  await set({ x: .35, y: .58 }, 400);
  const before = await point(); await set({ present: false }, 160);
  check(await held(), 'brief hand loss retains the object during grace');
  check(JSON.stringify(await point()) === JSON.stringify(before), 'missing hand never moves the object');
  await set({ present: true }, 100); check(await held(), 'return within grace continues hold');
  const beforeLong = await point(); await set({ present: false }, 400);
  check(!(await held()) && JSON.stringify(await point()) === JSON.stringify(beforeLong), 'long loss gently drops with zero throw');
  await set({ present: true, x: .35, y: .58 }, 150); check(!(await held()), 'reacquired held fist never auto-grab');
  await set({ closed: false }); await set({ closed: true }); await set({ x: .77, y: .38 }, 500); await set({ closed: false });
  check((await page.locator('.pw-task-number').textContent()) === '02', 'mirrored cover projection places circle in its socket');
  await set({ x: .2, y: .48 }); await set({ closed: true }); await set({ x: .8 }, 500);
  check((await point()).x < 389 && await held(), 'raw camera movement obeys barrier sweep');
  await set({ x: .2 }, 400); await set({ y: .84 }, 400); await set({ x: .8 }, 400); await set({ y: .48 }, 400); await set({ closed: false });
  check((await page.locator('.pw-task-number').textContent()) === '03', 'raw camera gap route works');
  await set({ x: .24, y: .65 }); await set({ closed: true }); await set({ x: .75, y: .33 }, 500); await set({ closed: false }); await page.clock.runFor(500);
  await page.locator('.platform-result').waitFor({ state: 'visible' });
  check((await page.locator('.arcade-result-source').textContent()).includes('CAMERA') && (await page.locator('.pw-receipt').textContent()).includes('WORLD COMPLETE'), 'raw camera round clears with source retained');
  check((await page.locator('.pw-receipt').textContent()).includes('1 tracking drops'), 'tracking drop is counted independently of deliberate releases');
  await page.waitForFunction(() => __contexts.every((c) => c.state === 'closed'));
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended') && __models === __closes && __rafs.size === 0), 'RESULT releases all tracks, model, audio and animation loops');
  await page.locator('[data-result-action="retry"]').click(); await page.waitForFunction(() => __mediaRequests === 2); await page.clock.runFor(100);
  check(await page.evaluate(() => __tracks.filter((t) => t.readyState === 'live').length === 1), 'camera RETRY opens only one new stream');
  await page.evaluate(() => { location.hash = '#/game/solo-blink-horror'; });
  await page.waitForFunction(() => document.querySelector('.launch-camera')?.disabled === false);
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended')), 'switching to BLINK stops PINCH camera before next permission');
  await page.locator('.launch-camera').click(); await page.waitForFunction(() => __mediaRequests === 3); await page.clock.runFor(100);
  check(await page.evaluate(() => __tracks.filter((t) => t.readyState === 'live').length === 1 && __models - __closes === 1), 'cross-game switch leaves exactly one camera and one model');
  await page.locator('.game-back').click();
  await page.evaluate(() => { __delay = true; location.hash = '#/game/solo-pinch-world'; });
  await page.waitForFunction(() => document.querySelector('.launch-camera')?.disabled === false);
  await page.locator('.launch-camera').click(); await page.waitForFunction(() => typeof __grant === 'function');
  await page.locator('.game-back').click(); await page.evaluate(() => __grant()); await page.clock.runFor(100);
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended') && __models === __closes), 'late hand-camera permission is cancelled and released');
  await page.evaluate(() => { __delay = false; __deny = true; location.hash = '#/game/solo-blink-horror'; });
  await page.waitForFunction(() => document.querySelector('.launch-camera')?.disabled === false);
  await page.locator('.launch-camera').click(); await page.locator('.bh-recovery').waitFor({ state: 'visible' });
  await page.locator('.bh-demo').click(); await page.clock.runFor(17000);
  await page.locator('.platform-result').waitFor({ state: 'visible' });
  const requests = await page.evaluate(() => __mediaRequests);
  await page.locator('[data-result-action="retry"]').click(); await page.clock.runFor(3000);
  check(await page.evaluate(() => __mediaRequests) === requests && (await page.locator('.bh-source').textContent()).includes('DEMO'), 'RETRY preserves in-game camera-denial → demo recovery');
  await page.locator('.game-back').click(); await page.clock.runFor(100);
  await page.waitForFunction(() => __contexts.every((c) => c.state === 'closed'));
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended') && [...document.querySelectorAll('video')].every((v) => !v.srcObject)), 'final exit leaves no stream on either game');
  await page.evaluate(() => clearInterval(__paint));
  check(errors.length === 0, 'no uncaught browser errors');
  return { checks, errors, synthetic: true, physicalDevice: false };
}
