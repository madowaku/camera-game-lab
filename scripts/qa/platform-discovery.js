// Playwright CLI run-code --filename. Use a disposable browser profile.
async (page) => {
  const base = new URL(page.url()).origin;
  const checks = [], errors = [], requests = [];
  const check = (value, name) => { if (!value) throw Error(name); checks.push(name); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  await page.evaluate(() => {
    for (const key of Object.keys(localStorage)) if (key.startsWith('camera-game-lab-platform-')) localStorage.removeItem(key);
    localStorage.setItem('camera-game-lab-locale', 'ja');
  });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto(base + '/#/feed/solo-hand-beat');
  await page.reload();
  await page.locator('.platform-onboarding').waitFor();
  await page.waitForFunction(() => document.querySelector('.preview-asset')?.naturalWidth > 0);
  await page.screenshot({ path: 'output/playwright/platform-onboarding-360.png' });
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 1 });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 180, y: 290 }] });
  for (let y = 270; y >= 70; y -= 20) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 180, y }] });
    await page.waitForTimeout(20);
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForFunction(() => document.querySelector('.lab-feed').scrollTop === 800);
  await page.waitForFunction(() => document.querySelector('.feed-card:not([inert])')?.dataset.id === 'voice-note-blaster');
  check(await page.locator('.platform-onboarding').count() === 0, 'touch swipe through onboarding dismisses it and snaps');
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: false });
  await cdp.detach();
  await page.locator('.lab-feed').focus(); await page.keyboard.press('ArrowUp');
  await page.waitForFunction(() => document.querySelector('.lab-feed').scrollTop === 0);
  await page.waitForFunction(() => document.querySelector('.feed-card:not([inert])')?.dataset.id === 'solo-hand-beat');
  await page.locator('.feed-card:not([inert]) [data-action="favorite"]').click();
  await page.reload();
  check(await page.locator('[data-id="solo-hand-beat"] [data-action="favorite"]').getAttribute('aria-pressed') === 'true', 'favorite persists');
  check(await page.locator('.platform-onboarding').count() === 0, 'onboarding stays dismissed');
  await page.waitForFunction(() => document.querySelector('.preview-asset')?.naturalWidth > 0);
  await page.screenshot({ path: 'output/playwright/platform-feed-360.png' });
  await page.locator('.lab-feed').focus(); await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => document.querySelector('.lab-feed').scrollTop === 800);
  await page.waitForFunction(() => document.querySelector('.feed-card:not([inert])')?.dataset.id === 'voice-note-blaster');
  check(await page.locator('.feed-card:not([inert])').getAttribute('data-id') === 'voice-note-blaster', 'keyboard advances exactly one game');
  await page.mouse.move(180, 350); await page.mouse.wheel(0, 800);
  await page.waitForFunction(() => document.querySelector('.lab-feed').scrollTop === 1600);
  await page.waitForFunction(() => document.querySelector('.feed-card:not([inert])')?.dataset.id === 'duo-tiny-bot-duel');
  check(await page.locator('.feed-card:not([inert])').getAttribute('data-id') === 'duo-tiny-bot-duel', 'wheel advances exactly one game');
  check(await page.locator('.preview-active').count() === 3, 'only current and adjacent previews animate');
  check(!requests.some(url => /mediapipe|\.wasm|\.task|soloExperience|duoArcade.*\.js|noteBlasterArcade.*\.js|bodyInput/.test(url)), 'discovery requests no game JS or MediaPipe models');
  await page.locator('.feed-card:not([inert]) [data-action="info"]').click();
  check(await page.locator('dialog').evaluate(el => el.open), 'INFO opens');
  await page.screenshot({ path: 'output/playwright/platform-info-360.png' });
  await page.keyboard.press('Escape');
  check(await page.locator('.feed-card:not([inert]) [data-action="info"]').evaluate(el => el === document.activeElement), 'INFO returns focus');
  await page.locator('.platform-locale').click();
  check(await page.locator('html').getAttribute('lang') === 'en', 'language changes to EN');
  check(await page.locator('.feed-card:not([inert])').getAttribute('data-id') === 'duo-tiny-bot-duel', 'language preserves discovery position');
  await page.evaluate(() => {
    Object.defineProperty(navigator, 'share', { configurable: true, value: undefined });
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__sharedText = text; } } });
  });
  await page.locator('.feed-card:not([inert]) [data-action="share"]').click();
  check((await page.evaluate(() => window.__sharedText)).includes('#/game/duo-tiny-bot-duel'), 'share copies canonical link');
  await page.locator('.feed-card:not([inert]) [data-action="play"]').click();
  await page.waitForFunction(() => document.querySelector('.launch-camera')?.disabled === false);
  check(await page.locator('.orientation-guide').isVisible(), 'DUO portrait guide appears after PLAY');
  await page.screenshot({ path: 'output/playwright/platform-duo-guide-360.png' });
  await page.setViewportSize({ width: 800, height: 360 });
  check(!(await page.locator('.orientation-guide').isVisible()), 'DUO guide hides in landscape');
  await page.setViewportSize({ width: 360, height: 800 });
  await page.locator('.game-back').click();
  check(await page.locator('.feed-card:not([inert])').getAttribute('data-id') === 'duo-tiny-bot-duel', 'back preserves position');
  for (const size of [{ width: 360, height: 800 }, { width: 720, height: 1280 }, { width: 1440, height: 900 }]) {
    await page.setViewportSize(size); await page.goto(base + '/#/feed/solo-hand-beat');
    await page.waitForFunction(() => document.querySelector('.preview-asset')?.naturalWidth > 0);
    await page.locator('.platform-toast.is-visible').waitFor({ state: 'hidden' });
    await page.screenshot({ path: `output/playwright/platform-feed-${size.width}.png` });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `no horizontal overflow ${size.width}`);
    check(await page.locator('.feed-card').first().evaluate(el => el.clientHeight === innerHeight), `one viewport per game ${size.width}`);
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check(await page.locator('.preview-active').count() === 0, 'reduced motion stops previews');
  await page.setViewportSize({ width: 360, height: 500 });
  await page.locator('.lab-feed').focus(); await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => { const cards = document.querySelectorAll('.feed-card'); return document.querySelector('.lab-feed').scrollTop === cards[1].offsetTop - cards[0].offsetTop; });
  await page.waitForFunction(() => document.querySelector('.feed-card:not([inert])')?.dataset.id === 'voice-note-blaster');
  check(await page.locator('.feed-card:not([inert])').getAttribute('data-id') === 'voice-note-blaster', 'short viewport uses real card position');
  await page.locator('.feed-card:not([inert]) [data-action="play"]').click();
  check(page.url().includes('/game/voice-note-blaster'), 'short viewport PLAY stays reachable');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.locator('[data-nav="explore"]').click();
  await page.locator('[data-input="BLINK"]').click();
  check(await page.locator('.explore-empty').isVisible(), 'empty filter has recovery');
  await page.locator('[data-input="ALL"]').click();
  await page.locator('#experiment-search').fill('guardian');
  check(await page.locator('.explore-card').count() === 1, 'search finds matching game');
  await page.locator('[data-clear]').click();
  check(await page.locator('.explore-card').count() === 8, 'clear restores all games');
  await page.screenshot({ path: 'output/playwright/platform-explore-360.png' });
  await page.goto(base + '/#/game/does-not-exist');
  check(await page.locator('.explore-page .sheet-play').isVisible(), 'invalid link has return path');
  await page.goto(base + '/#daitai');
  await page.waitForFunction(() => document.querySelector('.launch-demo')?.disabled === false);
  await page.clock.install();
  await page.locator('.launch-demo').click(); await page.clock.runFor(34000);
  check(await page.locator('.platform-result').isVisible(), 'Daitai demo completes');
  await page.screenshot({ path: 'output/playwright/platform-result-360.png' });
  await page.locator('[data-result-action="share"]').click();
  check((await page.evaluate(() => window.__sharedText)).includes('pts'), 'result share includes score');
  await page.locator('[data-result-action="retry"]').click();
  check(!(await page.locator('.platform-result').isVisible()), 'RETRY clears result');
  await page.clock.runFor(34000);
  check(await page.locator('.platform-result').isVisible(), 'retry completes again');
  await page.locator('[data-result-action="next"]').click();
  await page.locator('.lab-feed').waitFor();
  check(await page.locator('.feed-card:not([inert])').getAttribute('data-id') === 'solo-hand-beat', 'NEXT selects next feed game');
  check(errors.length === 0, 'no uncaught page errors: ' + errors.join(';'));
  return { checks, errors };
}
