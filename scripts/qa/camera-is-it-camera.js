// Synthetic rear feed + DeviceOrientationEvent enter the real browser input path.
async (page) => {
  const base = new URL(page.url()).origin, checks = [], errors = [];
  const check = (value, name) => { if (!value) throw Error(name); checks.push(name); };
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('camera-game-lab-locale', 'en'));
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto(base + '/?qa=camera-is-it-sensor&run=' + Date.now() + '#/game/outcam-the-camera-is-it');
  await page.waitForFunction(() => document.querySelector('.launch-camera') && !document.querySelector('.launch-camera').disabled);
  await page.clock.install();
  await page.evaluate(async () => {
    const { CameraIsItGame } = await import('/src/games/cameraIsIt.js');
    const step = CameraIsItGame.prototype.step;
    CameraIsItGame.prototype.step = function (dt) { window.__game = this; return step.call(this, dt); };
    const { CameraOrientation } = await import('/src/input/cameraOrientation.js');
    const start = CameraOrientation.prototype.start;
    CameraOrientation.prototype.start = function () { window.__input = this; return start.call(this); };
    window.__permission = 'granted'; window.__delay = false; window.__tracks = []; window.__mediaRequests = 0;
    Object.defineProperty(DeviceOrientationEvent, 'requestPermission', { configurable: true, value: async () => __permission });
    const canvas = document.createElement('canvas'); canvas.width = 360; canvas.height = 640;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#9da687'; ctx.fillRect(0, 0, 360, 640);
    window.__paint = setInterval(() => ctx.fillRect(0, 0, 360, 640), 30);
    const stream = () => { const s = canvas.captureStream(30); __tracks.push(...s.getTracks()); return s; };
    navigator.mediaDevices.getUserMedia = async (constraints) => {
      __mediaRequests++; window.__constraints = constraints;
      if (__delay) return new Promise((resolve) => { window.__grant = () => resolve(stream()); });
      return stream();
    };
    window.__look = { alpha: 0, beta: 90, gamma: 0 }; window.__emit = true;
    window.__sensors = setInterval(() => { if (__emit) dispatchEvent(new DeviceOrientationEvent('deviceorientation', __look)); }, 40);
  });
  await page.locator('.launch-camera').click(); await page.clock.runFor(200);
  await page.waitForFunction(() => document.querySelector('.ci-stage video')?.srcObject);
  await page.clock.runFor(1700);
  check(await page.evaluate(() => __game.phase === 'playing'), 'fresh posture starts the world');
  check(await page.evaluate(() => __constraints.audio === false && __constraints.video.facingMode.ideal === 'environment'), 'rear camera preferred, no microphone request');
  const x = await page.evaluate(() => __game.camera.x);
  await page.evaluate(() => { __look.alpha = -2; }); await page.clock.runFor(300);
  check(await page.evaluate((before) => __game.camera.x > before + 100, x), 'raw device yaw pans right');
  await page.locator('.ci-background').click();
  check(await page.locator('.ci-background').getAttribute('aria-pressed') === 'false', 'live background switches OFF');
  check(await page.evaluate(() => __tracks.some((t) => t.readyState === 'live') && __game.background === false), 'background OFF retains the same sensor and camera session for comparison');
  await page.locator('.ci-background').click();
  check(await page.locator('.ci-background').getAttribute('aria-pressed') === 'true', 'live background switches ON');
  await page.screenshot({ path: 'output/playwright/camera-is-it-360-camera.png' });
  await page.locator('.ci-center').click();
  const centered = await page.evaluate(() => __game.targetCamera.x); await page.clock.runFor(200);
  check(await page.evaluate((n) => Math.abs(__game.targetCamera.x - n) < .01, centered), 'recenter retains the current frame');
  await page.evaluate(() => { __emit = false; }); await page.clock.runFor(1700);
  check(await page.locator('.ci-resume').isVisible(), 'stale orientation pauses with explicit recovery');
  const time = await page.evaluate(() => __game.elapsed); await page.clock.runFor(2000);
  check(await page.evaluate((n) => __game.elapsed === n, time), 'stale sensor never advances the round');
  await page.evaluate(() => { __emit = true; }); await page.clock.runFor(100); await page.locator('.ci-resume').click();
  await page.clock.runFor(100);
  check(await page.evaluate(() => !__game.paused), 'fresh posture and Resume recover');
  await page.evaluate(() => { __look.alpha = -45; }); await page.clock.runFor(2000);
  await page.locator('.platform-result').waitFor({ state: 'visible' });
  check((await page.locator('.platform-result').textContent()).includes('Camera'), 'failure result preserves camera provenance');
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended') && !__input.video.srcObject && __input.abort.signal.aborted), 'result releases rear feed and orientation listener');
  await page.locator('[data-result-action="retry"]').click(); await page.clock.runFor(250); await page.clock.runFor(1600);
  check(await page.evaluate(() => __mediaRequests === 2 && __tracks.filter((t) => t.readyState === 'live').length === 1), 'camera RETRY creates exactly one new feed');
  await page.locator('.game-back').click();
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended')), 'exit stops the feed');
  await page.evaluate(() => { __delay = true; location.hash = '#/game/outcam-the-camera-is-it'; });
  await page.waitForFunction(() => !document.querySelector('.launch-camera')?.disabled);
  await page.locator('.launch-camera').click(); await page.clock.runFor(100);
  await page.waitForFunction(() => typeof __grant === 'function'); await page.locator('.game-back').click();
  await page.evaluate(() => __grant()); await page.clock.runFor(100);
  check(await page.evaluate(() => __tracks.every((t) => t.readyState === 'ended')), 'late rear-camera grant after navigation is cancelled');
  await page.evaluate(() => { __delay = false; __permission = 'denied'; location.hash = '#/game/outcam-the-camera-is-it'; });
  await page.waitForFunction(() => !document.querySelector('.launch-camera')?.disabled);
  const requests = await page.evaluate(() => __mediaRequests); await page.locator('.launch-camera').click();
  await page.locator('.ci-demo').waitFor({ state: 'visible' });
  check(await page.evaluate((n) => __mediaRequests === n, requests), 'orientation denial never opens the rear camera');
  await page.locator('.ci-demo').click(); await page.clock.runFor(14000);
  await page.locator('.platform-result').waitFor({ state: 'visible' });
  check((await page.locator('.platform-result').textContent()).includes('Demo'), 'permission denial can recover into an explicit demo');
  await page.locator('[data-result-action="retry"]').click(); await page.clock.runFor(1600);
  check(await page.evaluate((n) => __mediaRequests === n, requests), 'demo recovery RETRY keeps demo provenance');
  await page.locator('.game-back').click();
  await page.evaluate(() => { clearInterval(__paint); clearInterval(__sensors); });
  check(errors.length === 0, 'no uncaught synthetic sensor errors');
  return { checks, errors, synthetic: true, physicalDevice: false };
}
